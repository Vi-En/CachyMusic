import assert from 'node:assert/strict';
import { SOULSEEK_RESULT_BATCH, resultPageWindow, clampTransferProgress, transferActionSignature, isTransferFinished, isTransferPlayable } from '../scripts/modules/soulseek-ui-budget.js';
assert.equal(SOULSEEK_RESULT_BATCH, 60);
assert.deepEqual(resultPageWindow(10000), {page:0,start:0,end:60});
assert.deepEqual(resultPageWindow(10000, 1), {page:1,start:60,end:120});
assert.deepEqual(resultPageWindow(10000, 999), {page:166,start:9960,end:10000});
assert.deepEqual(resultPageWindow(3, 999), {page:0,start:0,end:3});
assert.deepEqual(resultPageWindow(Number.NaN, -1), {page:0,start:0,end:0});
assert.notEqual(transferActionSignature({status:'Complete',localFile:'a'}),transferActionSignature({status:'Complete',localFile:'b'}));
assert.equal(clampTransferProgress('80.5'), 80.5);
assert.equal(clampTransferProgress(undefined), 0);
assert.equal(clampTransferProgress('NaN'), 0);
assert.equal(clampTransferProgress(-70), 0);
assert.equal(clampTransferProgress(110), 100);
assert.equal(transferActionSignature({ status:'Downloading', progress: 90 }), transferActionSignature({ status:'Downloading', progress:100 }), 'Progress alone is not completion');
assert.equal(isTransferFinished({status:'Downloading',progress:100,isFinished:true}),false);
assert.equal(isTransferPlayable({status:'Finished',isFinished:true,localFile:'x',fileExists:false}),false);
assert.equal(isTransferPlayable({status:'Finished',isFinished:true,localFile:'x',fileExists:true}),true);
assert.notEqual(transferActionSignature({status:'Downloading',progress:100}),transferActionSignature({status:'Finished',isFinished:true,localFile:'x',fileExists:true}));
assert.equal(transferActionSignature({status:'Paused',progress:65}), transferActionSignature({status:'Paused',progress:65}));
console.log('PASS Soulseek result DOM budget, no result loss, percent normalization, completion-sensitive actions');
